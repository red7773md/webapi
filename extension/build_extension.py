"""Regenerate app/extension_files.py from the files in this folder.

Run after editing anything here:   python extension/build_extension.py
Vercel only bundles .py files, so the admin download cannot read this folder at runtime. The files
are embedded (base64) in app/extension_files.py instead, and app/extension_pack.py zips them.
"""

import base64
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "app" / "extension_files.py"
FILES = [
    "manifest.json",
    "manifest-firefox.json",
    "background.js",
    "content.js",
    "options.html",
    "options.js",
    "options.css",
    "icon.png",
    "README.md",
]


def main() -> None:
    lines = [
        '"""GENERATED by extension/build_extension.py. Do not edit by hand.',
        "",
        "The Gemini browser extension's files, base64-encoded, so the admin download can build a",
        'configured zip on Vercel."""',
        "",
        "FILES = {",
    ]
    for name in FILES:
        b64 = base64.b64encode((HERE / name).read_bytes()).decode()
        lines.append(f"    {name!r}: {b64!r},")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"built {len(FILES)} files into {OUT}")


if __name__ == "__main__":
    main()
